-- =============================================================
-- 碳排放披露数据血缘与版本影响管理平台 - PostgreSQL 表结构
-- 幂等：全部使用 IF NOT EXISTS，可随应用重复启动
-- =============================================================

CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(64)  UNIQUE NOT NULL,
  password_hash VARCHAR(128) NOT NULL,
  display_name  VARCHAR(64)  NOT NULL,
  role          VARCHAR(32)  NOT NULL          -- ADMIN / ANALYST / AUDITOR / FINANCE
);

CREATE TABLE IF NOT EXISTS plants (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code   VARCHAR(32) UNIQUE NOT NULL,
  name   VARCHAR(128) NOT NULL,
  region VARCHAR(32)  NOT NULL                 -- 电网/地域分区，如 CN-EAST / CN-WEST
);

CREATE TABLE IF NOT EXISTS product_lines (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(32) UNIQUE NOT NULL,
  name VARCHAR(128) NOT NULL
);

-- 来源批次：工厂上传的燃料/用电/采购活动数据
CREATE TABLE IF NOT EXISTS source_batches (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_no          VARCHAR(64) UNIQUE NOT NULL,
  plant_id          BIGINT NOT NULL REFERENCES plants(id),
  category          VARCHAR(32) NOT NULL,      -- FUEL / ELECTRICITY / PROCUREMENT
  period            VARCHAR(16) NOT NULL,      -- YYYY-MM
  status            VARCHAR(32) NOT NULL,      -- UPLOADED/VERIFIED/REJECTED/CONFLICT/SUPERSEDED/VOID
  uploaded_by       VARCHAR(64) NOT NULL,
  uploaded_at       TIMESTAMP NOT NULL DEFAULT now(),
  verified_by       VARCHAR(64),
  verified_at       TIMESTAMP,
  replaces_batch_id BIGINT,                    -- 修订指向被替换批次
  revision_no       INT NOT NULL DEFAULT 0,
  void_reason       VARCHAR(512),
  row_count         INT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_batches_period ON source_batches(period);
CREATE INDEX IF NOT EXISTS idx_batches_replaces ON source_batches(replaces_batch_id);

-- 来源行：批次内的活动数据明细
CREATE TABLE IF NOT EXISTS source_rows (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id        BIGINT NOT NULL REFERENCES source_batches(id),
  row_no          INT NOT NULL,
  plant_id        BIGINT NOT NULL,
  product_line_id BIGINT,                      -- 为空表示工厂级未分摊
  scope           VARCHAR(16) NOT NULL,        -- SCOPE1 / SCOPE2 / SCOPE3
  energy_type     VARCHAR(32) NOT NULL,
  quantity        NUMERIC(18,3) NOT NULL,
  unit            VARCHAR(16) NOT NULL,
  voucher_no      VARCHAR(64),                 -- 采购行的供应商凭证号
  equipment_code  VARCHAR(64),                 -- 共享/租赁设备编号；为空表示工厂级活动
  period          VARCHAR(16) NOT NULL,
  status          VARCHAR(32) NOT NULL DEFAULT 'ACTIVE'   -- ACTIVE / SUPERSEDED / VOID
);
CREATE INDEX IF NOT EXISTS idx_rows_batch   ON source_rows(batch_id);
CREATE INDEX IF NOT EXISTS idx_rows_period  ON source_rows(period);
CREATE INDEX IF NOT EXISTS idx_rows_voucher ON source_rows(voucher_no);

-- 排放因子目录
CREATE TABLE IF NOT EXISTS factors (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR(64) UNIQUE NOT NULL,
  name        VARCHAR(128) NOT NULL,
  scope       VARCHAR(16) NOT NULL,
  energy_type VARCHAR(32) NOT NULL,
  region      VARCHAR(32) NOT NULL,
  unit        VARCHAR(16) NOT NULL
);

-- 因子版本：地域 + 适用期 + 审批状态
CREATE TABLE IF NOT EXISTS factor_versions (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  factor_id           BIGINT NOT NULL REFERENCES factors(id),
  version_no          INT NOT NULL,
  value               NUMERIC(18,6) NOT NULL,  -- kgCO2e / 单位活动量
  valid_from          DATE NOT NULL,
  valid_to            DATE,
  status              VARCHAR(32) NOT NULL,    -- DRAFT / APPROVED / REPLACED / RETIRED
  created_by          VARCHAR(64) NOT NULL,
  created_at          TIMESTAMP NOT NULL DEFAULT now(),
  approved_by         VARCHAR(64),
  approved_at         TIMESTAMP,
  replaces_version_id BIGINT,
  UNIQUE(factor_id, version_no)
);

-- 核算运行
CREATE TABLE IF NOT EXISTS calc_runs (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_no       VARCHAR(64) UNIQUE NOT NULL,
  period       VARCHAR(16) NOT NULL,
  purpose      VARCHAR(16) NOT NULL DEFAULT 'OFFICIAL',  -- OFFICIAL / CANDIDATE
  status       VARCHAR(32) NOT NULL,                     -- RUNNING / COMPLETED / FAILED
  triggered_by VARCHAR(64) NOT NULL,
  created_at   TIMESTAMP NOT NULL DEFAULT now(),
  started_at   TIMESTAMP,
  completed_at TIMESTAMP,
  error        VARCHAR(1024)
);
-- 同一期间同一时刻只允许一个官方运行处于 RUNNING
CREATE UNIQUE INDEX IF NOT EXISTS one_running_official_per_period
  ON calc_runs(period) WHERE status = 'RUNNING' AND purpose = 'OFFICIAL';

-- 运行启动时绑定的因子清单（快照）：运行中替换因子不影响本运行
CREATE TABLE IF NOT EXISTS run_factor_bindings (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id            BIGINT NOT NULL REFERENCES calc_runs(id),
  factor_version_id BIGINT NOT NULL,
  factor_code       VARCHAR(64) NOT NULL,
  region            VARCHAR(32) NOT NULL,
  energy_type       VARCHAR(32) NOT NULL,
  value             NUMERIC(18,6) NOT NULL,
  valid_from        DATE,
  valid_to          DATE
);
CREATE INDEX IF NOT EXISTS idx_bindings_run    ON run_factor_bindings(run_id);
CREATE INDEX IF NOT EXISTS idx_bindings_fver   ON run_factor_bindings(factor_version_id);

-- 排放结果（带血缘）
CREATE TABLE IF NOT EXISTS emission_results (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id            BIGINT NOT NULL REFERENCES calc_runs(id),
  plant_id          BIGINT NOT NULL,
  product_line_id   BIGINT,
  scope             VARCHAR(16) NOT NULL,
  energy_type       VARCHAR(32) NOT NULL,
  activity_qty      NUMERIC(18,3) NOT NULL,
  unit              VARCHAR(16) NOT NULL,
  factor_version_id BIGINT,
  factor_value      NUMERIC(18,6),
  emission_tco2e    NUMERIC(18,6),
  status            VARCHAR(32) NOT NULL,      -- OK / PENDING_FACTOR / PENDING_OWNERSHIP（待裁定，未并入集团趋势）
  classification    VARCHAR(16) NOT NULL DEFAULT 'INCLUDED'  -- INCLUDED / EXCLUDED / PENDING（责任归属口径）
);
CREATE INDEX IF NOT EXISTS idx_results_run ON emission_results(run_id);
CREATE INDEX IF NOT EXISTS idx_results_class ON emission_results(classification);

-- 血缘：结果 ← 来源行
CREATE TABLE IF NOT EXISTS emission_lineage (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  result_id     BIGINT NOT NULL REFERENCES emission_results(id),
  source_row_id BIGINT NOT NULL,
  qty_used      NUMERIC(18,3) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_lineage_result ON emission_lineage(result_id);
CREATE INDEX IF NOT EXISTS idx_lineage_row    ON emission_lineage(source_row_id);

-- 披露报告
CREATE TABLE IF NOT EXISTS reports (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code       VARCHAR(64) UNIQUE NOT NULL,
  title      VARCHAR(256) NOT NULL,
  period     VARCHAR(16) NOT NULL,
  status     VARCHAR(32) NOT NULL,             -- DRAFT/PENDING_REVIEW/RECONCILE_FAILED/APPROVED/PUBLISHED
  created_by VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT now()
);

-- 报告版本：冻结的运行结果快照，发布后不可改写
CREATE TABLE IF NOT EXISTS report_versions (
  id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id                 BIGINT NOT NULL REFERENCES reports(id),
  version_no                INT NOT NULL,
  run_id                    BIGINT NOT NULL,
  status                    VARCHAR(32) NOT NULL,   -- FROZEN / PUBLISHED / SUPERSEDED / RESTATED
  total_scope1              NUMERIC(18,6) NOT NULL DEFAULT 0,
  total_scope2              NUMERIC(18,6) NOT NULL DEFAULT 0,
  total_scope3              NUMERIC(18,6) NOT NULL DEFAULT 0,
  total_tco2e               NUMERIC(18,6) NOT NULL DEFAULT 0,
  reconcile_status          VARCHAR(32) NOT NULL,   -- OK / MISMATCH / PENDING_FACTOR / PENDING_OWNERSHIP
  reconcile_diff            NUMERIC(18,6) NOT NULL DEFAULT 0,
  pending_count             INT NOT NULL DEFAULT 0,
  frozen_by                 VARCHAR(64) NOT NULL,
  frozen_at                 TIMESTAMP NOT NULL DEFAULT now(),
  published_at              TIMESTAMP,
  restatement_of_version_id BIGINT,
  note                      VARCHAR(1024),
  UNIQUE(report_id, version_no)
);
-- 同一报告同一时刻只有一个已发布版本
CREATE UNIQUE INDEX IF NOT EXISTS one_published_per_report
  ON report_versions(report_id) WHERE status = 'PUBLISHED';

CREATE TABLE IF NOT EXISTS report_items (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_version_id BIGINT NOT NULL REFERENCES report_versions(id),
  plant_id          BIGINT NOT NULL,
  product_line_id   BIGINT,
  scope             VARCHAR(16) NOT NULL,
  energy_type       VARCHAR(32) NOT NULL,
  activity_qty      NUMERIC(18,3) NOT NULL,
  emission_tco2e    NUMERIC(18,6),
  item_status       VARCHAR(32) NOT NULL       -- OK / PENDING_FACTOR
);
CREATE INDEX IF NOT EXISTS idx_items_version ON report_items(report_version_id);

-- 勾稽结果：产品线合计 vs 工厂明细
CREATE TABLE IF NOT EXISTS reconciliations (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_version_id  BIGINT NOT NULL REFERENCES report_versions(id),
  product_line_id    BIGINT,
  label              VARCHAR(256) NOT NULL,
  plant_detail_sum   NUMERIC(18,6) NOT NULL,
  product_line_total NUMERIC(18,6) NOT NULL,
  diff               NUMERIC(18,6) NOT NULL,
  status             VARCHAR(32) NOT NULL      -- OK / MISMATCH / PENDING_FACTOR / PENDING_OWNERSHIP
);
CREATE INDEX IF NOT EXISTS idx_recon_version ON reconciliations(report_version_id);

-- 影响评估：来源或因子变化后对指标与已发布报告的影响
CREATE TABLE IF NOT EXISTS impact_assessments (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trigger_type     VARCHAR(32) NOT NULL,       -- SOURCE_SUPPLEMENT / SOURCE_REVISION / SOURCE_MISSING / FACTOR_REVISION
  trigger_ref      VARCHAR(256) NOT NULL,
  period           VARCHAR(16) NOT NULL,
  status           VARCHAR(32) NOT NULL,       -- OPEN / ACKNOWLEDGED / RESOLVED
  summary          VARCHAR(1024),
  candidate_run_id BIGINT,
  created_at       TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS impact_items (
  id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  impact_id                 BIGINT NOT NULL REFERENCES impact_assessments(id),
  plant_id                  BIGINT,
  product_line_id           BIGINT,
  scope                     VARCHAR(16),
  metric                    VARCHAR(256) NOT NULL,
  old_value                 NUMERIC(18,6),
  new_value                 NUMERIC(18,6),
  diff                      NUMERIC(18,6),
  affected_report_id        BIGINT,
  affected_report_version_id BIGINT
);
CREATE INDEX IF NOT EXISTS idx_impact_items ON impact_items(impact_id);

-- 重述建议：已发布报告发现差异后生成，不能直接覆盖已发布报告
CREATE TABLE IF NOT EXISTS restatements (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id        BIGINT NOT NULL,
  impact_id        BIGINT NOT NULL,
  reason           VARCHAR(1024),
  diff_summary     VARCHAR(2048),
  status           VARCHAR(32) NOT NULL,       -- PROPOSED / ACCEPTED / REJECTED / RESOLVED
  candidate_run_id BIGINT,
  new_version_id   BIGINT,
  created_by       VARCHAR(64),
  created_at       TIMESTAMP NOT NULL DEFAULT now(),
  resolved_at      TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_restate_report ON restatements(report_id);

-- =============================================================
-- 责任归属（运营控制边界）：不可变事件 + 按报告截止点推导控制状态
-- 设计取舍：保存不可变的收购/剥离/移交/计量/租赁/裁定事件，
-- 在查询/冻结/核算时按截止点推导当时控制状态，修订理由完整、历史可复演；
-- 不把当前股权反挂到全部历史，也不把事件流预先物化成“唯一正确”的区间表。
-- =============================================================

-- 责任主体：集团内法人/工厂，或集团外原股东/出租方
CREATE TABLE IF NOT EXISTS ownership_parties (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR(64) UNIQUE NOT NULL,
  name        VARCHAR(128) NOT NULL,
  party_type  VARCHAR(16) NOT NULL,              -- GROUP=集团内 / EXTERNAL=集团外
  created_at  TIMESTAMP NOT NULL DEFAULT now()
);

-- 不可变责任事件：登记后只能被更正事件/裁定事件修正，事件本身不更新不删除
CREATE TABLE IF NOT EXISTS ownership_events (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_no        VARCHAR(64) UNIQUE NOT NULL,
  event_type      VARCHAR(32) NOT NULL,          -- 见 Types.OwnershipEventType
  plant_id        BIGINT NOT NULL REFERENCES plants(id),
  equipment_code  VARCHAR(64),                   -- 共享/租赁设备编号；为空表示工厂级事件
  evidence_type   VARCHAR(32) NOT NULL,          -- LEGAL/ASSET/LEASE/HANDOVER/METERING/RULING/CORRECTION
  evidence_no     VARCHAR(128) NOT NULL,         -- 证据文号（股权交割书/产权证/租赁合同/交接单/停计量通知/裁定书）
  effective_date  DATE NOT NULL,                 -- 证据生效日（区间端点）
  counterparty    VARCHAR(128),                  -- 交易对手/出租方/原股东
  payload         VARCHAR(2048),                 -- 事件结构化参数（JSON：目标主体/计量安排/更正指向等）
  conflict_with   BIGINT,                        -- 相反法律证据：指向冲突事件 id（不能被多数票覆盖）
  supersedes_event_id BIGINT,                    -- 追溯更正事件指向被更正事件
  status          VARCHAR(16) NOT NULL,          -- ACTIVE / RULED（被裁定覆盖后标记，事件行仍保留）
  created_by      VARCHAR(64) NOT NULL,
  created_at      TIMESTAMP NOT NULL DEFAULT now(),
  note            VARCHAR(1024)
);
CREATE INDEX IF NOT EXISTS idx_own_events_plant ON ownership_events(plant_id);
CREATE INDEX IF NOT EXISTS idx_own_events_date  ON ownership_events(effective_date);
CREATE INDEX IF NOT EXISTS idx_own_events_type  ON ownership_events(event_type);

-- 责任裁定：控制权与设备交接不一致的时段只能待裁定；相反法律证据不能被多数票覆盖
CREATE TABLE IF NOT EXISTS ownership_rulings (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ruling_no        VARCHAR(64) UNIQUE NOT NULL,
  plant_id         BIGINT NOT NULL REFERENCES plants(id),
  equipment_code   VARCHAR(64),
  period_start     DATE NOT NULL,                -- 待裁定区间（含端点）
  period_end       DATE NOT NULL,
  decision         VARCHAR(32) NOT NULL,         -- INCLUDE=纳入集团 / EXCLUDE=排除集团 / PENDING=仍待裁定
  evidence_no      VARCHAR(128) NOT NULL,        -- 裁定依据文号
  reason           VARCHAR(1024),
  status           VARCHAR(16) NOT NULL,         -- ACTIVE / SUPERSEDED（被后续裁定取代，行保留）
  supersedes_ruling_id BIGINT,
  created_by       VARCHAR(64) NOT NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rulings_plant ON ownership_rulings(plant_id);

-- 活动责任归属明细：核算时按责任区间交集切分每条活动量的落点
CREATE TABLE IF NOT EXISTS activity_allocations (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id           BIGINT NOT NULL REFERENCES calc_runs(id),
  result_id        BIGINT REFERENCES emission_results(id),
  source_row_id    BIGINT NOT NULL,
  plant_id         BIGINT NOT NULL,
  product_line_id  BIGINT,
  scope            VARCHAR(16) NOT NULL,
  energy_type      VARCHAR(32) NOT NULL,
  period           VARCHAR(16) NOT NULL,         -- 活动发生期间 YYYY-MM
  segment_start    DATE NOT NULL,                -- 切分后的责任片段（含端点）
  segment_end      DATE NOT NULL,
  days_in_month    INT NOT NULL,                 -- 该期间总天数（按天均摊依据）
  days_in_segment  INT NOT NULL,                 -- 片段天数
  activity_qty     NUMERIC(18,3) NOT NULL,       -- 按天比例切分后的活动量
  unit             VARCHAR(16) NOT NULL,
  emission_tco2e   NUMERIC(18,6),                 -- 该片段排放（待裁定/缺因子时为空，仅作参照不进合计）
  factor_version_id BIGINT,
  classification   VARCHAR(16) NOT NULL,         -- INCLUDED / EXCLUDED / PENDING
  party_id         BIGINT REFERENCES ownership_parties(id),  -- 承担运营控制的一方（待裁定可为空）
  basis            VARCHAR(2048)                 -- 归属依据说明（命中的事件/裁定/缺口原因）
);
CREATE INDEX IF NOT EXISTS idx_alloc_run   ON activity_allocations(run_id);
CREATE INDEX IF NOT EXISTS idx_alloc_row   ON activity_allocations(source_row_id);
CREATE INDEX IF NOT EXISTS idx_alloc_class ON activity_allocations(classification);

-- 报告版本责任归属汇总：冻结时固化，冻结后补入的活动/裁定只能生成新比较版本
CREATE TABLE IF NOT EXISTS report_ownership_summaries (
  id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_version_id           BIGINT NOT NULL UNIQUE REFERENCES report_versions(id),
  period                      VARCHAR(16) NOT NULL,
  included_tco2e              NUMERIC(18,6) NOT NULL DEFAULT 0,  -- 纳入合并报表
  excluded_tco2e              NUMERIC(18,6) NOT NULL DEFAULT 0,  -- 排除（非集团运营控制）
  pending_tco2e               NUMERIC(18,6) NOT NULL DEFAULT 0,  -- 待裁定（不并入集团趋势）
  included_activity           NUMERIC(18,3) NOT NULL DEFAULT 0,
  excluded_activity           NUMERIC(18,3) NOT NULL DEFAULT 0,
  pending_activity            NUMERIC(18,3) NOT NULL DEFAULT 0,
  pending_segment_count       INT NOT NULL DEFAULT 0,
  derived_as_of               TIMESTAMP NOT NULL,                -- 推导所用报告截止点（事件流复演锚点）
  created_at                  TIMESTAMP NOT NULL DEFAULT now()
);

-- 可比性注释：解释未决几天为何没有并入任一集团趋势、年中收购/剥离口径变化
CREATE TABLE IF NOT EXISTS comparability_notes (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_version_id  BIGINT NOT NULL REFERENCES report_versions(id),
  plant_id           BIGINT,
  note_type          VARCHAR(32) NOT NULL,      -- PENDING_GAP / ACQUISITION / DIVESTITURE / SHARED_EQUIPMENT / RULING / EXCLUSION
  content            VARCHAR(2048) NOT NULL,
  segment_start      DATE,
  segment_end        DATE,
  created_at         TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notes_version ON comparability_notes(report_version_id);

